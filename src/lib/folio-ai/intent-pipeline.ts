/**
 * Robustly sanitizes and repairs common malformed JSON generated by small on-device models:
 * - strips markdown code blocks (```json ... ```)
 * - removes trailing commas before } and ]
 * - turns single quotes around keys/values into double quotes
 * - handles unclosed brackets or trailing ellipses
 */
export function sanitizeModelJson(raw: string): string {
  let text = raw.trim();
  // Strip markdown code fences
  text = text.replace(/```(?:json)?\s*([\s\S]*?)\s*```/gi, "$1").trim();
  // Strip opening/closing markers if present inside
  text = text.replace(/\[\/?AI_ACTION_PLAN\]/gi, "").trim();

  // Remove JS/C-style comments
  text = text.replace(/\/\/[^\n]*/g, "");
  text = text.replace(/\/\*[\s\S]*?\*\//g, "");

  // Remove trailing commas in objects and arrays
  text = text.replace(/,\s*([}\]])/g, "$1");

  // Fix single quotes for JSON keys and string values
  text = text.replace(/'([^'\\]*(?:\\.[^'\\]*)*)'/g, (_match, group: string) => {
    return `"${group.replace(/"/g, '\\"')}"`;
  });

  return text;
}

/**
 * Multi-strategy action plan extractor.
 * Tries explicit tags, balanced braces, markdown blocks, and bare JSON,
 * returning validated actions or null if no valid plan can be extracted.
 */
export function repairAndExtractActionPlan(content: string): { id: string; params: Record<string, unknown> }[] | null {
  if (!content || typeof content !== "string") return null;

  // Strategy 1: Explicit [AI_ACTION_PLAN] tags
  const startTag = content.indexOf(AI_ACTION_PLAN_OPEN);
  if (startTag >= 0) {
    const endTag = content.lastIndexOf(AI_ACTION_PLAN_CLOSE);
    let raw = "";
    if (endTag > startTag) {
      raw = content.slice(startTag + AI_ACTION_PLAN_OPEN.length, endTag);
    } else {
      // Model forgot closing tag or generation stopped early: extract from open tag to balanced brace
      raw = content.slice(startTag + AI_ACTION_PLAN_OPEN.length);
      const firstBrace = raw.indexOf("{");
      if (firstBrace >= 0) {
        let depth = 0;
        let lastPos = -1;
        for (let i = firstBrace; i < raw.length; i++) {
          if (raw[i] === "{") depth++;
          else if (raw[i] === "}") {
            depth--;
            if (depth === 0) {
              lastPos = i + 1;
              break;
            }
          }
        }
        if (lastPos > firstBrace) {
          raw = raw.slice(firstBrace, lastPos);
        }
      }
    }

    const plan = parseAndValidatePlanJson(raw);
    if (plan) return plan;
  }

  // Strategy 2: Markdown code block with JSON containing actions
  const codeBlockMatch = content.match(/```(?:json)?\s*(\{[\s\S]*?"actions"[\s\S]*?\})\s*```/i);
  if (codeBlockMatch) {
    const plan = parseAndValidatePlanJson(codeBlockMatch[1]);
    if (plan) return plan;
  }

  // Strategy 3: Bare JSON object with "actions" array
  const bareJsonMatch = content.match(/\{[\s\r\n]*"actions"\s*:[\s\S]*?\][\s\r\n]*\}/);
  if (bareJsonMatch) {
    const plan = parseAndValidatePlanJson(bareJsonMatch[0]);
    if (plan) return plan;
  }

  // Strategy 4: Direct array of actions: [{"id": ...}]
  const arrayMatch = content.match(/\[\s*\{[\s\S]*?"id"[\s\S]*?\}\s*\]/);
  if (arrayMatch) {
    const plan = parseAndValidatePlanJson(arrayMatch[0]);
    if (plan) return plan;
  }

  return null;
}

function parseAndValidatePlanJson(raw: string): { id: string; params: Record<string, unknown> }[] | null {
  const sanitized = sanitizeModelJson(raw);
  try {
    const parsed: unknown = JSON.parse(sanitized);
    let actionList: unknown[] = [];
    if (Array.isArray(parsed)) {
      actionList = parsed;
    } else if (parsed && typeof parsed === "object") {
      const obj = parsed as Record<string, unknown>;
      if (Array.isArray(obj.actions)) {
        actionList = obj.actions;
      } else if (obj.plan && typeof obj.plan === "object" && Array.isArray((obj.plan as Record<string, unknown>).actions)) {
        actionList = (obj.plan as Record<string, unknown>).actions as unknown[];
      }
    }

    if (!actionList.length) return null;

    // Normalize IDs before validation
    const normalizedList = actionList.map(item => {
      if (item && typeof item === "object" && typeof (item as Record<string, unknown>).id === "string") {
        return {
          ...(item as Record<string, unknown>),
          id: normalizeActionId((item as Record<string, unknown>).id as string),
        };
      }
      return item;
    });

    return validateActionPlan(normalizedList);
  } catch {
    return null;
  }
}

/**
 * Natural language intent parser for explicit workspace requests.
 * Runs when the local model produced a conversational reply without an action plan,
 * resolving references against the user's real workspace context.
 */
export function parseNaturalLanguageIntent(
  userPrompt: string,
  context?: WorkspaceSummaryContext,
): IntentParseResult | null {
  const text = userPrompt.trim();
  const lower = text.toLowerCase();

  // Check if intent is to add tasks to an existing project before checking new project creation
  const isAddTasksToExisting =
    /\b(create|add|make|insert)\b.*\b(?:task|tasks)\b.*\b(?:in|to)\b.*(?:\bproject\b)/i.test(lower) ||
    /\b(?:in|to)\s+(?:my\s+)?existing\s+project\b/i.test(lower);

  // 1. Create project (with or without tasks)
  // e.g., "Create a project called Website Redesign with five tasks, assign appropriate priorities, and give the project a description."
  // e.g., "Create a project called Website Redesign."
  // e.g., "Create a project with five tasks."
  const isCreateProject =
    !isAddTasksToExisting &&
    /\b(create|start|make|set up|new)\b.*\bproject\b/i.test(lower) &&
    !/\b(convert|turn)\b/i.test(lower);

  if (isCreateProject) {
    // Extract project name
    let projectName = "";
    const nameMatch =
      text.match(/(?:called|named|titled)\s+["'“]?([^"'”\n,.]+?)["'”]?\s*(?:with|\.|\,|$)/i) ??
      text.match(/project\s+["'“]([^"'”\n]+?)["'”]/i) ??
      text.match(/(?:create|start|make|new)\s+(?:a\s+)?project\s+([A-Z][A-Za-z0-9\s-]+?)(?:\s+with|\.|\,|$)/);

    if (nameMatch) {
      projectName = nameMatch[1].trim();
    } else {
      // Look for a fallback title
      const simpleMatch = text.match(/project\s+([^,.\n]+)/i);
      if (simpleMatch && !/\b(with|\d+|tasks)\b/i.test(simpleMatch[1])) {
        projectName = simpleMatch[1].trim();
      }
    }

    if (!projectName || /\b(with|five|three|tasks)\b/i.test(projectName)) {
      projectName = "New Project";
    }

    // Extract description
    let description = "";
    const descMatch =
      text.match(/(?:description|details|notes)[:\s]+["'“]?([^"'”\n]+)["'”]?/i) ??
      text.match(/give (?:it|the project) a description\s*(?:of\s*)?["'“]?([^"'”\n]+)["'”]?/i);
    if (descMatch) {
      description = descMatch[1].trim();
    } else if (/description/i.test(lower)) {
      description = `Workspace project for ${projectName}.`;
    }

    // Extract priority
    let priority: Priority = "Medium";
    if (/\b(urgent|highest priority)\b/i.test(lower)) priority = "High";
    else if (/\bhigh priority\b|\bpriority\s*:\s*high\b/i.test(lower)) priority = "High";
    else if (/\blow priority\b|\bpriority\s*:\s*low\b/i.test(lower)) priority = "Low";

    // Extract due date
    let dueDate: string | null = null;
    const dateMatch = text.match(/\b(due\s*(?:date\s*)?(?:on\s*|by\s*|:\s*)?)(\d{4}-\d{2}-\d{2})\b/i);
    if (dateMatch) {
      dueDate = dateMatch[2];
    }

    // Extract tasks
    const tasks: { title: string; priority: TaskPriority; dueDate?: string | null; description?: string }[] = [];
    const taskCountWordMatch = text.match(/\b(one|two|three|four|five|six|seven|eight|nine|ten|\d+)\s+tasks\b/i);
    let taskCount = 0;
    if (taskCountWordMatch) {
      const wordMap: Record<string, number> = {
        one: 1, two: 2, three: 3, four: 4, five: 5,
        six: 6, seven: 7, eight: 8, nine: 9, ten: 10,
      };
      taskCount = wordMap[taskCountWordMatch[1].toLowerCase()] ?? parseInt(taskCountWordMatch[1], 10);
    }

    // Check for enumerated tasks (e.g. 1. Design brief 2. Wireframes 3. Prototypes)
    const enumTasks = Array.from(text.matchAll(/(?:^|\n|\d+[\.)]|\-)\s*["'“]?([A-Z][^,\n\.\d]+?)["'”]?\s*(?=\d+[\.)]|\-|\n|$)/g))
      .map(m => m[1].trim())
      .filter(t => t.length > 2 && !/^(create|project|task|tasks|with|assign|give)/i.test(t));

    if (enumTasks.length >= 2) {
      const prioritiesList: TaskPriority[] = ["High", "Medium", "Medium", "Low", "None"];
      for (let i = 0; i < enumTasks.length; i++) {
        tasks.push({
          title: enumTasks[i],
          priority: prioritiesList[i % prioritiesList.length],
        });
      }
    } else if (taskCount > 0) {
      const defaultTaskTitles = [
        `Discovery & scope definition for ${projectName}`,
        `Architecture & wireframe design`,
        `Core implementation & setup`,
        `Quality testing & review`,
        `Launch & rollout deployment`,
        `Documentation & handoff`,
        `User feedback review`,
      ];
      const prioritiesList: TaskPriority[] = ["High", "High", "Medium", "Medium", "Low"];
      for (let i = 0; i < Math.min(taskCount, 10); i++) {
        tasks.push({
          title: defaultTaskTitles[i] ?? `Milestone step ${i + 1}`,
          priority: prioritiesList[i % prioritiesList.length],
          dueDate: dueDate ?? undefined,
        });
      }
    }

    const actions: { id: string; params: Record<string, unknown> }[] = [
      {
        id: "create_project",
        params: {
          name: projectName,
          description,
          priority,
          dueDate,
        },
      },
    ];

    if (tasks.length > 0) {
      actions.push({
        id: "create_tasks",
        params: {
          tasks: tasks.map(t => ({
            title: t.title,
            priority: t.priority,
            dueDate: t.dueDate ?? null,
            projectId: "$project.id",
          })),
        },
      });
    }

    return {
      actions,
      rationale: tasks.length
        ? `Creates project “${projectName}” and ${tasks.length} associated tasks.`
        : `Creates project “${projectName}”.`,
      source: "intent_parser",
    };
  }

  // 2. Add tasks to an EXISTING project
  // e.g., "Create three tasks in my existing project Website Redesign"
  // e.g., "Add 3 tasks to project Website Redesign"
  const isAddTasksToProject =
    /\b(create|add|make|insert)\b.*\b(?:task|tasks)\b.*\b(?:in|to)\b.*(?:\bproject\b)/i.test(lower);

  if (isAddTasksToProject || isAddTasksToExisting) {
    const projectWordMatch =
      text.match(/(?:(?:my\s+)?existing\s+project|project)\s+["'“]?([A-Za-z0-9\s-]+?)["'”]?\s*(?:\.|\,|$)/i) ??
      text.match(/(?:in|to)\s+(?:project\s+)?["'“]?([A-Za-z0-9\s-]+?)["'”]?\s*(?:\.|\,|$)/i);
    const targetProjectName = projectWordMatch ? projectWordMatch[1].trim().replace(/^my\s+/i, "") : "";

    const matchedProject = context?.projects?.find(p =>
      text.toLowerCase().includes(p.name.toLowerCase()) ||
      (targetProjectName && (p.name.toLowerCase() === targetProjectName.toLowerCase() || p.name.toLowerCase().includes(targetProjectName.toLowerCase()) || targetProjectName.toLowerCase().includes(p.name.toLowerCase()))),
    );

    if (!matchedProject) {
      return {
        actions: [],
        clarification: targetProjectName
          ? `I couldn't find an existing project matching “${targetProjectName}” in your workspace. Would you like me to create this project first, or pick an existing project?`
          : "Which project would you like me to add these tasks to?",
        source: "clarification",
      };
    }

    const countMatch = text.match(/\b(one|two|three|four|five|six|seven|eight|nine|ten|\d+)\s+tasks\b/i);
    const wordMap: Record<string, number> = {
      one: 1, two: 2, three: 3, four: 4, five: 5,
      six: 6, seven: 7, eight: 8, nine: 9, ten: 10,
    };
    const taskCount = countMatch
      ? (wordMap[countMatch[1].toLowerCase()] ?? parseInt(countMatch[1], 10))
      : 3;

    const taskTitles = [
      `Review requirements for ${matchedProject.name}`,
      `Prepare implementation plan`,
      `Execute review & verification`,
    ];

    const tasks = Array.from({ length: Math.min(taskCount, 10) }, (_, i) => ({
      title: taskTitles[i] ?? `Next step ${i + 1} for ${matchedProject.name}`,
      priority: (i === 0 ? "High" : "Medium") as TaskPriority,
      projectId: matchedProject.id,
    }));

    return {
      actions: [
        {
          id: "create_tasks",
          params: { tasks },
        },
      ],
      rationale: `Creates ${tasks.length} tasks in project “${matchedProject.name}”.`,
      source: "intent_parser",
    };
  }

  // 3. Complete / Mark task as done
  // e.g., "Mark my specified task as completed"
  // e.g., "Complete task Fix tab bar spacing"
  const isCompleteTask =
    /\b(mark|complete|finish|check off|done)\b.*\btask\b/i.test(lower) ||
    /\btask\b.*\b(completed|done|finished)\b/i.test(lower);

  if (isCompleteTask) {
    const taskTitleMatch =
      text.match(/(?:task|called|named)\s+["'“]?([^"'”\n]+?)["'”]?\s*(?:as|\.|\,|$)/i);
    const query = taskTitleMatch ? taskTitleMatch[1].trim() : "";

    let matchedTask = query
      ? context?.tasks?.find(t => t.title.toLowerCase().includes(query.toLowerCase()))
      : undefined;

    if (!matchedTask && context?.tasks?.length) {
      // Pick first non-completed task if specific one is requested generically
      matchedTask = context.tasks.find(t => t.status !== "done") ?? context.tasks[0];
    }

    if (!matchedTask) {
      return {
        actions: [],
        clarification: "Which task would you like to mark as completed?",
        source: "clarification",
      };
    }

    return {
      actions: [
        {
          id: "complete_task",
          params: { taskId: matchedTask.id },
        },
      ],
      rationale: `Marks task “${matchedTask.title}” as completed.`,
      source: "intent_parser",
    };
  }

  // 4. Update task priority
  // e.g., "Update the priority of my specified task"
  // e.g., "Set priority of task X to High"
  const isUpdatePriority =
    /\b(priority|urgent|high|medium|low)\b/i.test(lower) &&
    /\b(update|change|set|make)\b.*\b(task|priority)\b/i.test(lower);

  if (isUpdatePriority) {
    let targetPriority: TaskPriority = "High";
    if (/\b(urgent)\b/i.test(lower)) targetPriority = "Urgent";
    else if (/\b(high)\b/i.test(lower)) targetPriority = "High";
    else if (/\b(medium)\b/i.test(lower)) targetPriority = "Medium";
    else if (/\b(low)\b/i.test(lower)) targetPriority = "Low";

    const titleMatch = text.match(/(?:task|called|named)\s+["'“]?([^"'”\n]+?)["'”]?\s*(?:to|\.|\,|$)/i);
    const query = titleMatch ? titleMatch[1].trim() : "";

    let matchedTask = query
      ? context?.tasks?.find(t => t.title.toLowerCase().includes(query.toLowerCase()))
      : undefined;

    if (!matchedTask && context?.tasks?.length) {
      matchedTask = context.tasks[0];
    }

    if (!matchedTask) {
      return {
        actions: [],
        clarification: "Which task would you like to update?",
        source: "clarification",
      };
    }

    return {
      actions: [
        {
          id: "update_task",
          params: { taskId: matchedTask.id, priority: targetPriority },
        },
      ],
      rationale: `Updates priority of task “${matchedTask.title}” to ${targetPriority}.`,
      source: "intent_parser",
    };
  }

  // 5. Create reminder for task
  // e.g., "Create a reminder for a task."
  // e.g., "Remind me 1 hour before task X"
  const isCreateReminder =
    /\b(reminder|remind me|set a reminder|create a reminder)\b/i.test(lower);

  if (isCreateReminder) {
    let timing = "1h_before";
    if (/15\s*m/i.test(lower)) timing = "15m_before";
    else if (/30\s*m/i.test(lower)) timing = "30m_before";
    else if (/1\s*d|day before/i.test(lower)) timing = "1d_before";
    else if (/at due|due time/i.test(lower)) timing = "at_due";

    const titleMatch =
      text.match(/(?:task)\s+["'“]?([^"'”\n]+?)["'”]?\s*(?:\.|\,|$)/i) ??
      text.match(/(?:for)\s+["'“]?([^"'”\n]+?)["'”]?\s*(?:\.|\,|$)/i);
    const query = titleMatch ? titleMatch[1].trim().replace(/^task\s+/i, "").replace(/["'”]/g, "") : "";

    let matchedTask = context?.tasks?.find(t =>
      text.toLowerCase().includes(t.title.toLowerCase()) ||
      (query && (t.title.toLowerCase() === query.toLowerCase() || t.title.toLowerCase().includes(query.toLowerCase())))
    );

    if (!matchedTask && context?.tasks?.length) {
      matchedTask = context.tasks[0];
    }

    if (!matchedTask) {
      return {
        actions: [],
        clarification: "Which task would you like me to set a reminder for?",
        source: "clarification",
      };
    }

    return {
      actions: [
        {
          id: "create_reminder",
          params: { taskId: matchedTask.id, timing, enabled: true },
        },
      ],
      rationale: `Sets a reminder for task “${matchedTask.title}”.`,
      source: "intent_parser",
    };
  }

  // 6. Convert idea to project
  // e.g., "Turn this idea into a project."
  // e.g., "Convert idea 'Mobile App' into a project."
  const isConvertIdea =
    /\b(turn|convert|make)\b.*\bidea\b.*\b(into|to)\b.*\bproject\b/i.test(lower);

  if (isConvertIdea) {
    const titleMatch = text.match(/idea\s+["'“]?([^"'”\n]+?)["'”]?\s*(?:into|to|\.|\,|$)/i);
    const query = titleMatch ? titleMatch[1].trim() : "";

    let matchedIdea = query
      ? context?.ideas?.find(i => i.title.toLowerCase().includes(query.toLowerCase()))
      : undefined;

    if (!matchedIdea && context?.ideas?.length) {
      matchedIdea = context.ideas[0];
    }

    if (!matchedIdea) {
      return {
        actions: [],
        clarification: "Which idea would you like to convert into a project?",
        source: "clarification",
      };
    }

    return {
      actions: [
        {
          id: "convert_idea",
          params: { ideaId: matchedIdea.id },
        },
      ],
      rationale: `Converts idea “${matchedIdea.title}” into a project.`,
      source: "intent_parser",
    };
  }

  // 7. Create idea
  // e.g., "Create an idea about a mobile application."
  // e.g., "Capture an idea: Offline sync for mobile"
  const isCreateIdea =
    /\b(create|capture|add|save|new)\b.*\bidea\b/i.test(lower);

  if (isCreateIdea) {
    let ideaTitle = "";
    const match =
      text.match(/(?:about|called|named|titled|idea:)\s+["'“]?([^"'”\n.]+?)["'”]?\s*(?:\.|\,|$)/i) ??
      text.match(/idea\s+["'“]([^"'”\n]+?)["'”]/i);
    if (match) {
      ideaTitle = match[1].trim();
    } else {
      const fallback = text.replace(/^(create|capture|add|new|an?)\s+idea\s*(about|for)?/i, "").trim();
      ideaTitle = fallback.slice(0, 80) || "Mobile Application Architecture";
    }

    return {
      actions: [
        {
          id: "create_idea",
          params: {
            title: ideaTitle,
            description: `Idea spark captured via Folio AI: ${ideaTitle}`,
            category: "Product",
            color: "yellow",
          },
        },
      ],
      rationale: `Captures idea “${ideaTitle}”.`,
      source: "intent_parser",
    };
  }

  return null;
}
